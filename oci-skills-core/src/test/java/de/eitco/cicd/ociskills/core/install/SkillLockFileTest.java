package de.eitco.cicd.ociskills.core.install;

import de.eitco.cicd.ociskills.core.SkillPullException;
import de.eitco.cicd.ociskills.core.TestSkills;
import de.eitco.cicd.ociskills.core.oci.Digest;
import de.eitco.cicd.ociskills.core.oci.SkillStatus;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.FileTime;
import java.time.Instant;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class SkillLockFileTest {

    private static final Digest DIGEST_A = Digest.parse("sha256:" + "a".repeat(64));
    private static final Digest DIGEST_B = Digest.parse("sha256:" + "b".repeat(64));

    private static final LockedSkill NEXUS_TEST = new LockedSkill("[1.0,2.0)", SkillStatus.PUBLISHED,
            new SkillOrigin(new SkillId("cicd", "nexus-test"), "1.2.0", SkillStatus.PUBLISHED, DIGEST_A, "eitco-maven"));
    private static final LockedSkill ALPHA = new LockedSkill("1.10", SkillStatus.DRAFT,
            new SkillOrigin(new SkillId("cicd", "alpha"), "1.10", SkillStatus.DRAFT, DIGEST_B, "eitco-oci"));

    @TempDir
    Path tempDirectory;

    private Path file() {
        return tempDirectory.resolve(SkillLockFile.DEFAULT_FILE_NAME);
    }

    @Test
    void writesTheSkillsSortedById() throws Exception {
        new SkillLockFile(file()).write(List.of(NEXUS_TEST, ALPHA));

        assertThat(file()).hasContent("""
                # generated by oci-skills-maven-plugin - commit it, update it with mvn oci-skills:update
                skills:
                - id: cicd/alpha
                  requested:
                    version: "1.10"
                    status: draft
                  version: "1.10"
                  status: draft
                  digest: sha256:%s
                  source: eitco-oci
                - id: cicd/nexus-test
                  requested:
                    version: "[1.0,2.0)"
                    status: published
                  version: 1.2.0
                  status: published
                  digest: sha256:%s
                  source: eitco-maven
                """.formatted("b".repeat(64), "a".repeat(64)));
    }

    @Test
    void readsWhatItWrites() throws Exception {
        SkillLockFile lockFile = new SkillLockFile(file());
        lockFile.write(List.of(NEXUS_TEST, ALPHA));

        assertThat(lockFile.read()).containsExactly(ALPHA, NEXUS_TEST);
    }

    @Test
    void writesTheRequestedRepository() throws Exception {
        LockedSkill located = new LockedSkill("1.0.0", SkillStatus.PUBLISHED, "teams/acme/skills",
                NEXUS_TEST.resolved());
        SkillLockFile lockFile = new SkillLockFile(file());
        lockFile.write(List.of(located));

        assertThat(file()).hasContent("""
                # generated by oci-skills-maven-plugin - commit it, update it with mvn oci-skills:update
                skills:
                - id: cicd/nexus-test
                  requested:
                    version: 1.0.0
                    status: published
                    repository: teams/acme/skills
                  version: 1.2.0
                  status: published
                  digest: sha256:%s
                  source: eitco-maven
                """.formatted("a".repeat(64)));
        assertThat(lockFile.read()).containsExactly(located);
        assertThat(file()).content().doesNotContain("location");
    }

    @Test
    void writesTheRequestedLocation() throws Exception {
        LockedSkill located = new LockedSkill("1.0.0", SkillStatus.PUBLISHED, null,
                "de.eitco.cicd.it:cicd-skills:nexus-test", NEXUS_TEST.resolved());
        SkillLockFile lockFile = new SkillLockFile(file());
        lockFile.write(List.of(located));

        assertThat(file()).hasContent("""
                # generated by oci-skills-maven-plugin - commit it, update it with mvn oci-skills:update
                skills:
                - id: cicd/nexus-test
                  requested:
                    version: 1.0.0
                    status: published
                    location: de.eitco.cicd.it:cicd-skills:nexus-test
                  version: 1.2.0
                  status: published
                  digest: sha256:%s
                  source: eitco-maven
                """.formatted("a".repeat(64)));
        assertThat(lockFile.read()).containsExactly(located);
    }

    @Test
    void readsLockFilesWithoutLocation() throws Exception {
        TestSkills.write(tempDirectory, SkillLockFile.DEFAULT_FILE_NAME, """
                skills:
                - id: cicd/nexus-test
                  requested:
                    version: 1.0.0
                    status: published
                    repository: teams/acme/skills
                  version: 1.2.0
                  status: published
                  digest: sha256:%s
                  source: eitco-maven
                """.formatted("a".repeat(64)));

        assertThat(new SkillLockFile(file()).read()).singleElement()
                .satisfies(locked -> assertThat(locked.requestedLocation()).isNull());
    }

    @Test
    void readsNothingFromAMissingFile() throws Exception {
        assertThat(new SkillLockFile(file()).read()).isEmpty();
    }

    @Test
    void keepsTheFileIfNothingChanged() throws Exception {
        SkillLockFile lockFile = new SkillLockFile(file());
        lockFile.write(List.of(NEXUS_TEST));
        FileTime past = FileTime.from(Instant.parse("2020-01-01T00:00:00Z"));
        Files.setLastModifiedTime(file(), past);

        lockFile.write(List.of(NEXUS_TEST));

        assertThat(Files.getLastModifiedTime(file())).isEqualTo(past);
    }

    @Test
    void reportsInvalidFiles() {
        TestSkills.write(tempDirectory, SkillLockFile.DEFAULT_FILE_NAME, """
                skills:
                - id: nexus-test
                """);

        assertThatThrownBy(() -> new SkillLockFile(file()).read())
                .isInstanceOf(SkillPullException.class)
                .hasMessageContaining(SkillLockFile.DEFAULT_FILE_NAME);
    }
}
