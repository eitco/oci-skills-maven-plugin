package de.eitco.cicd.ociskills.core.skillcard;

import de.eitco.cicd.ociskills.core.SkillValidationException;
import de.eitco.cicd.ociskills.core.oci.SkillStatus;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Pattern;

/**
 * Validates the {@link SkillCard} generated for a skill and the skill directory against the rules of the skill image
 * and the agent skills format. All problems are collected and reported together.
 */
public class SkillValidator {

    /**
     * A DNS label as defined in RFC 1123: lower case alphanumerics and {@code -}, starting and ending with an
     * alphanumeric character, at most 63 characters.
     */
    private static final Pattern DNS_LABEL = Pattern.compile("[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?");

    private static final String FRONTMATTER = SkillCard.PROMPT_FILE + " frontmatter: ";

    /**
     * The maximum length of a description in the agent skills format.
     */
    static final int MAX_DESCRIPTION_LENGTH = 1024;

    /**
     * @param frontmatter    the frontmatter of the skill's {@code SKILL.md}
     * @param settings       the values of the SkillCard that are configured in the plugin
     * @param skillDirectory the skill directory containing {@code SKILL.md}
     * @throws SkillValidationException listing every problem found
     */
    public void validate(SkillFrontmatter frontmatter, SkillCardSettings settings, Path skillDirectory)
            throws SkillValidationException {
        List<String> problems = new ArrayList<>();
        SkillMetadata metadata = SkillCard.of(frontmatter, settings).metadata();

        String directoryName = skillDirectory.getFileName() == null ? "" : skillDirectory.getFileName().toString();
        if (validateDnsLabel(FRONTMATTER + "name", metadata.name(), problems)
                && !metadata.name().equals(directoryName)) {
            problems.add(FRONTMATTER + "name '" + metadata.name() + "' must match the name of the skill directory '"
                    + directoryName + "'");
        }
        if (isBlank(metadata.description())) {
            problems.add(FRONTMATTER + "description is missing");
        } else if (metadata.description().length() > MAX_DESCRIPTION_LENGTH) {
            problems.add(FRONTMATTER + "description has " + metadata.description().length()
                    + " characters, at most " + MAX_DESCRIPTION_LENGTH + " are allowed");
        }
        for (String key : SkillMarkdownWriter.MANAGED_METADATA) {
            if (frontmatter.metadata().containsKey(key)) {
                problems.add(FRONTMATTER + "metadata." + key + " is managed by the plugin - remove it and configure <"
                        + key + "> in the plugin");
            }
        }
        if (frontmatter.status() != null) {
            try {
                SkillStatus.parse(frontmatter.status());
            } catch (IllegalArgumentException e) {
                problems.add(FRONTMATTER + e.getMessage());
            }
        }
        validateDnsLabel("namespace", metadata.namespace(), problems);
        if (isBlank(metadata.version())) {
            problems.add("version is missing");
        }

        if (Files.exists(skillDirectory.resolve(SkillCard.FILE_NAME), LinkOption.NOFOLLOW_LINKS)) {
            problems.add(SkillCard.FILE_NAME + " is generated by the plugin - remove it from " + skillDirectory
                    + ", put name and description into the frontmatter of " + SkillCard.PROMPT_FILE
                    + " and configure namespace and version in the plugin");
        }
        validatePromptFile(skillDirectory, problems);

        if (!problems.isEmpty()) {
            throw new SkillValidationException(problems);
        }
    }

    /**
     * @return whether the value is valid
     */
    private static boolean validateDnsLabel(String field, String value, List<String> problems) {
        if (isBlank(value)) {
            problems.add(field + " is missing");
            return false;
        }
        if (!DNS_LABEL.matcher(value).matches()) {
            problems.add(field + " '" + value + "' is not a valid DNS label (lower case alphanumerics and '-', "
                    + "starting and ending alphanumeric, at most 63 characters)");
            return false;
        }
        return true;
    }

    private static void validatePromptFile(Path skillDirectory, List<String> problems) {
        try {
            Path root = skillDirectory.toAbsolutePath().normalize();
            Path file = root.resolve(SkillCard.PROMPT_FILE);
            if (!Files.exists(file)) {
                problems.add(SkillCard.PROMPT_FILE + " does not exist in the skill directory");
                return;
            }
            if (!file.toRealPath().startsWith(root.toRealPath())) {
                problems.add(SkillCard.PROMPT_FILE + " is a symbolic link pointing outside of the skill directory");
                return;
            }
            if (!Files.isRegularFile(file)) {
                problems.add(SkillCard.PROMPT_FILE + " is not a regular file");
            }
        } catch (IOException e) {
            problems.add(SkillCard.PROMPT_FILE + " cannot be resolved: " + e.getMessage());
        }
    }

    private static boolean isBlank(String value) {
        return value == null || value.isBlank();
    }
}
