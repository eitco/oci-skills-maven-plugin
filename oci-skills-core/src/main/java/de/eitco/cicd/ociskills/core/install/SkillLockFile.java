package de.eitco.cicd.ociskills.core.install;

import com.fasterxml.jackson.annotation.JsonInclude;
import com.fasterxml.jackson.annotation.JsonPropertyOrder;
import de.eitco.cicd.ociskills.core.SkillPullException;
import de.eitco.cicd.ociskills.core.oci.Digest;
import de.eitco.cicd.ociskills.core.oci.SkillStatus;
import tools.jackson.core.JacksonException;
import tools.jackson.databind.DeserializationFeature;
import tools.jackson.databind.MapperFeature;
import tools.jackson.dataformat.yaml.YAMLMapper;
import tools.jackson.dataformat.yaml.YAMLWriteFeature;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import java.util.Objects;

/**
 * Reads and writes the lock file {@code skills.lock.yaml}, which pins the resolved version and digest of every
 * requested skill. It is meant to be committed, so updates of skills are visible in reviews.
 */
public class SkillLockFile {

    public static final String DEFAULT_FILE_NAME = "skills.lock.yaml";

    private static final String HEADER =
            "# generated by oci-skills-maven-plugin - commit it, update it with mvn oci-skills:update\n";

    private static final YAMLMapper YAML = YAMLMapper.builder()
            .disable(MapperFeature.SORT_PROPERTIES_ALPHABETICALLY)
            .disable(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES)
            .disable(YAMLWriteFeature.WRITE_DOC_START_MARKER)
            .disable(YAMLWriteFeature.SPLIT_LINES)
            .enable(YAMLWriteFeature.MINIMIZE_QUOTES)
            .enable(YAMLWriteFeature.ALWAYS_QUOTE_NUMBERS_AS_STRINGS)
            .build();

    private final Path file;

    public SkillLockFile(Path file) {
        this.file = file;
    }

    /**
     * @return the locked skills - empty if the file does not exist
     */
    public List<LockedSkill> read() throws SkillPullException {
        if (!Files.isRegularFile(file)) {
            return List.of();
        }
        try {
            LockJson lock = YAML.readValue(file.toFile(), LockJson.class);
            List<LockedSkill> skills = new ArrayList<>();
            for (EntryJson entry : lock.skills() == null ? List.<EntryJson>of() : lock.skills()) {
                skills.add(entry.toLockedSkill());
            }
            return List.copyOf(skills);
        } catch (JacksonException | IllegalArgumentException | NullPointerException e) {
            throw new SkillPullException(file + " is invalid - fix it or delete it and run oci-skills:update: "
                    + e.getMessage(), e);
        }
    }

    /**
     * Writes the skills sorted by id. The file is not touched if its content would not change.
     */
    public void write(List<LockedSkill> skills) throws SkillPullException {
        List<EntryJson> entries = skills.stream()
                .sorted(Comparator.comparing(skill -> skill.id().toString()))
                .map(EntryJson::of)
                .toList();
        try {
            byte[] content = (HEADER + YAML.writeValueAsString(new LockJson(entries)))
                    .getBytes(StandardCharsets.UTF_8);
            if (Files.isRegularFile(file) && Arrays.equals(Files.readAllBytes(file), content)) {
                return;
            }
            Files.write(file, content);
        } catch (IOException | JacksonException e) {
            throw new SkillPullException("writing " + file + " failed: " + e, e);
        }
    }

    private record LockJson(List<EntryJson> skills) {
    }

    @JsonPropertyOrder({"id", "requested", "version", "status", "digest", "source"})
    private record EntryJson(String id, RequestedJson requested, String version, String status, String digest,
                             String source) {

        static EntryJson of(LockedSkill skill) {
            SkillOrigin resolved = skill.resolved();
            return new EntryJson(resolved.id().toString(),
                    new RequestedJson(skill.requestedVersion(), skill.requestedStatus().value(),
                            skill.requestedRepository(), skill.requestedLocation()),
                    resolved.version(), resolved.status().value(), resolved.digest().toString(), resolved.source());
        }

        LockedSkill toLockedSkill() {
            Objects.requireNonNull(requested, "requested of " + id);
            return new LockedSkill(Objects.requireNonNull(requested.version(), "requested version of " + id),
                    SkillStatus.parse(requested.status()), requested.repository(), requested.location(),
                    new SkillOrigin(SkillId.parse(id), Objects.requireNonNull(version, "version of " + id),
                            SkillStatus.parse(status), Digest.parse(Objects.requireNonNull(digest, "digest of " + id)),
                            source));
        }
    }

    @JsonPropertyOrder({"version", "status", "repository", "location"})
    private record RequestedJson(String version, String status,
                                 @JsonInclude(JsonInclude.Include.NON_NULL) String repository,
                                 @JsonInclude(JsonInclude.Include.NON_NULL) String location) {
    }
}
